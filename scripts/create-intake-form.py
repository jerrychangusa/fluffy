"""Rebuild the customer form and its portable runtime asset. Requires reportlab."""
from pathlib import Path
import base64, hashlib, json
from reportlab.pdfgen import canvas
from reportlab.lib.colors import HexColor, white

root = Path(__file__).resolve().parents[1]
path = root / 'assets' / 'prescription-intake.pdf'
c = canvas.Canvas(str(path), pagesize=(612, 792))
c.setTitle('Prescription intake | Customer information')
c.setAuthor('Support')
c.setSubject('intake-form/1')
ink, muted, green = map(HexColor, ['#17212e', '#5b6777', '#166b57'])
c.setFillColor(green); c.rect(0, 748, 612, 44, fill=1, stroke=0)
c.setFillColor(white); c.setFont('Helvetica-Bold', 11); c.drawString(44, 764, 'SUPPORT  /  PRESCRIPTION INTAKE')
c.setFillColor(ink); c.setFont('Helvetica-Bold', 26); c.drawString(44, 702, 'A few details, then we can help.')
c.setFont('Helvetica', 11); c.setFillColor(muted)
for i, line in enumerate(['Complete the fields below, save this PDF, and attach it to your email reply.', 'Please also attach a clear photo or PDF of your prescription if requested.']):
    c.drawString(44, 675 - i * 17, line)
form = c.acroForm

def field(name, label, y, hint=None):
    c.setFillColor(ink); c.setFont('Helvetica-Bold', 11); c.drawString(44, y + 43, label)
    form.textfield(name=name, tooltip=label, x=44, y=y, width=524, height=32,
        borderStyle='solid', borderWidth=1, borderColor=HexColor('#ccd5df'),
        fillColor=HexColor('#f8fafb'), textColor=ink, fontName='Helvetica', fontSize=12,
        forceBorder=True, maxlen=80)
    if hint:
        c.setFillColor(muted); c.setFont('Helvetica', 9); c.drawString(44, y - 16, hint)

field('order_reference', 'Order number', 572, 'Use the order number from your support email.')
field('customer_name', 'Your name', 476)
field('pd_text', 'Pupillary distance (PD), in millimeters', 380, 'Enter your existing measurement, exactly as provided (for example: 62 or 31 / 31).')
c.setFillColor(muted); c.setFont('Helvetica', 10)
for i,line in enumerate(['If you do not know your PD, leave the field blank and tell us in your email.', 'Please do not guess a measurement. Our team can help with the next step.']):
    c.drawString(44, 330-i*16, line)
field('completed_date', 'Date completed', 240, 'For example: October 18, 2026')
c.setStrokeColor(HexColor('#dde3e9')); c.line(44, 166, 568, 166)
c.setFillColor(ink); c.setFont('Helvetica-Bold', 10); c.drawString(44, 144, 'What happens next')
c.setFillColor(muted); c.setFont('Helvetica', 10)
for i,line in enumerate(['Your support agent will collect your information and coordinate with the review team.', 'Submitting this form does not confirm that a prescription has been clinically reviewed.']):
    c.drawString(44, 125-i*16, line)
c.setFont('Helvetica', 8); c.drawString(44, 48, 'Prescription intake / Form version 1')
c.save()
raw = path.read_bytes()
(root / 'assets' / 'intake-form.mjs').write_text('// Generated by scripts/create-intake-form.py; do not edit by hand.\nexport const INTAKE_FORM = ' + json.dumps({'filename':path.name,'content_type':'application/pdf','content_base64':base64.b64encode(raw).decode()}) + ';\nexport const INTAKE_FORM_SHA256 = ' + json.dumps(hashlib.sha256(raw).hexdigest()) + ';\n')
print(f'Created {path.name}: {len(raw)} bytes')
